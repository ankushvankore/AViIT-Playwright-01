/*
do-while loop
It is exit oriented loop
It is going to execute the statements first and then going to check the condition.
It is going to execute the loop at least one irrespective of the condition
Syntax:
do{
    statement/s;
}(condition);
*/

let i = 1;

do{
    console.log(i);
    i++;
}while(i<=10);

